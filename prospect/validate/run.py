"""Write docs/VALIDATION.md.

Usage: python -m prospect.validate.run (make validate)

Reads the database and local files only (the sensitivity results come from
make sensitivity). Revenue values are simulated, gross, before the host
share, and unvalidated.
"""

from datetime import date
from pathlib import Path

from prospect.db import connect
from prospect.priors import config
from prospect.validate import (
    baseline,
    calibration,
    energy,
    limits,
    sensitivity,
    stability,
    stress,
)

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "docs" / "VALIDATION.md"


def wins(part: dict) -> tuple[list[str], list[str]]:
    """Segments (30 or more buildings) where the model's median error is
    lower than size-only's, and where it is not."""
    better, not_better = [], []
    for g, v in part.items():
        if g == "all" or v["model"]["n"] < calibration.MIN_N:
            continue
        (better if v["model"]["mdape"] < v["size"]["mdape"] else not_better).append(g)
    return better, not_better


def summary(r: dict, cfg: dict) -> list[str]:
    e = r["energy"]["pilot"]["all"]
    s = r["energy"]["statewide"]["all"]
    better, not_better = wins(r["energy"]["pilot"])
    cal = r["calibration"]["all"]
    firm = {k: sum(x["p_top15"] > 0.5 for x in v) for k, v in r["stability"].items()}
    st = r["stress"]["regions"]
    tol = cfg["validate"]["calibration_tolerance"]["value"]
    calibrated = abs(cal["hit"] - 0.8) <= tol
    return [
        "## Summary",
        "",
        f"- Annual energy, towns held out: on {e['model']['n']} pilot buildings"
        f" the model ranks with Spearman {e['model']['spearman']:.2f} against"
        f" {e['size']['spearman']:.2f} for size-only, and its median error is"
        f" {e['model']['mdape']:.0%} against {e['size']['mdape']:.0%}"
        f" (statewide method check, {s['model']['n']:,} buildings:"
        f" {s['model']['spearman']:.2f} against {s['size']['spearman']:.2f}).",
        "- Where the model is closer than size-only (segments of 30 or more"
        f" buildings): {', '.join(better) or 'none'}. Where it is not:"
        f" {', '.join(not_better) or 'none'}. Within one segment the two rank"
        " buildings alike.",
        f"- Calibration: the 80 percent energy band holds the measured value"
        f" {cal['hit']:.0%} of the time, so it is"
        + (" calibrated overall." if calibrated else " not calibrated."),
        "- Rank stability: sites in the top 15 in more than half the draws,"
        f" Metro South {firm['metro_south']}, Worcester {firm['worcester']}."
        + "".join(
            f" {stability.REGIONS[k]}'s ranking is a tier, not an order."
            for k, n in firm.items()
            if n == 0
        ),
        "- Peak shape is unvalidated, only stress-tested: with the reduction"
        f" share cut, Metro South keeps {st['metro_south']['top15_kept']} of its"
        f" top 15 and Worcester {st['worcester']['top15_kept']}.",
        "- Value per block has no accuracy number. It is simulated, gross,"
        " before the host share, and unvalidated.",
    ]


def render(r: dict, cfg: dict) -> str:
    head = [
        "# Validation",
        "",
        f"Generated by `make validate` on {date.today().isoformat()} from the"
        " local database. It tests what public data can test and says what it"
        " cannot. Everything about revenue is simulated.",
    ]
    sections = [
        summary(r, cfg),
        baseline.section(r["baseline"]),
        energy.section(r["energy"]),
        calibration.section(r["calibration"], cfg),
        stability.section(r["stability"]),
        stress.section(r["stress"]),
        limits.PEAK_SHAPE,
        sensitivity.section(),
        limits.UNVALIDATED,
        limits.LIMITS,
    ]
    body = [line for s in sections for line in ["", *s]]
    return "\n".join(head + body) + "\n"


def main() -> None:
    cfg = config.load()
    with connect() as conn:
        r = {
            "baseline": baseline.results(conn),
            "energy": energy.results(conn),
            "calibration": calibration.results(conn, cfg),
            "stability": stability.results(conn, cfg),
            "stress": stress.results(conn, cfg),
        }
    PAGE.write_text(render(r, cfg))
    print(f"wrote {PAGE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
