"""Write docs/VALIDATION.md.

Usage: python -m prospect.validate.run (make validate)

Reads the database and local files only. Revenue values are simulated,
gross, before the host share, and unvalidated.
"""

from datetime import date
from pathlib import Path

from prospect.db import connect
from prospect.priors import config
from prospect.validate import baseline, calibration, energy, stability, stress

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "docs" / "VALIDATION.md"


def render(sections: list[list[str]]) -> str:
    head = [
        "# Validation",
        "",
        f"Generated by `make validate` on {date.today().isoformat()} from the"
        " local database. It tests what public data can test and says what it"
        " cannot. There is no accuracy number for value per block: revenue"
        " values are simulated, gross, before the host share, and unvalidated.",
    ]
    body = [line for s in sections for line in ["", *s]]
    return "\n".join(head + body) + "\n"


def main() -> None:
    cfg = config.load()
    with connect() as conn:
        sections = [
            baseline.section(baseline.results(conn)),
            energy.section(energy.results(conn)),
            calibration.section(calibration.results(conn, cfg), cfg),
            stability.section(stability.results(conn, cfg)),
            stress.section(stress.results(conn, cfg)),
        ]
    PAGE.write_text(render(sections))
    print(f"wrote {PAGE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
