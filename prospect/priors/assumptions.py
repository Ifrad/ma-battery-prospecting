"""Write docs/ASSUMPTIONS.md from the status, source and notes in config/.

Usage: python -m prospect.priors.assumptions
"""

from pathlib import Path

from prospect.priors import config

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "docs" / "ASSUMPTIONS.md"


def flat(text) -> str:
    return " ".join(str(text).split())


def render(configs: dict) -> str:
    placeholders, sourced = [], []
    for name, tree in configs.items():
        for path, prefix, node in config.entries(tree):
            row = (f"{name}.yaml: {path or '(top)'}", prefix, node)
            if node[prefix + "status"] == "placeholder":
                placeholders.append(row)
            else:
                sourced.append(row)
    out = [
        "# Assumptions",
        "",
        "Generated by `make assumptions` from config/*.yaml. Edit the config"
        " notes, not this page.",
        "",
        "Every model input is either sourced, with the document it was read"
        " from, or a placeholder: a value not read from a cited source, kept"
        f" visible until something better replaces it. There are"
        f" {len(placeholders)} placeholders and {len(sourced)} sourced values.",
        "",
        "## Placeholders",
    ]
    for title, prefix, node in placeholders:
        value = config.summary(node, prefix)
        out += ["", f"### {title}", ""]
        if value:
            out.append(f"- Value: {value}")
        out += [
            f"- What and why: {flat(node[prefix + 'note'])}",
            f"- How it gets tested: {flat(node[prefix + 'test'])}",
            f"- What would replace it: {flat(node[prefix + 'replace'])}",
        ]
    out += ["", "## Sourced values"]
    for title, prefix, node in sourced:
        value = config.summary(node, prefix)
        out += ["", f"### {title}", ""]
        if value:
            out.append(f"- Value: {value}")
        out.append(f"- Source: {flat(node[prefix + 'source'])}")
        if node.get(prefix + "note"):
            out.append(f"- Note: {flat(node[prefix + 'note'])}")
    return "\n".join(out) + "\n"


def main() -> None:
    PAGE.write_text(render(config.load()))
    print(f"wrote {PAGE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
