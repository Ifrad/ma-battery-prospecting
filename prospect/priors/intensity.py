"""Derive yearly kWh per sq ft by segment from LBER measured electricity.

Usage: python -m prospect.priors.intensity

Reads the database only. Writes config/intensity.yaml. Pilot candidate
buildings with measured grid electricity give each segment's spread, using
our building area; hospital and other_healthcare use LBER's statewide
Healthcare rows instead, and food production, cold storage and laundry
borrow the manufacturing spread as a proxy.
"""

import sys
from pathlib import Path

import numpy as np
import yaml

from prospect.db import connect

ROOT = Path(__file__).resolve().parents[2]
CONFIG_OUT = ROOT / "config" / "intensity.yaml"
MIN_BUILDINGS = 30
HEALTHCARE = ("hospital", "other_healthcare")
PROXY_FOR = ("food_production", "cold_storage", "laundry")
PROXY = "manufacturing"


def spread(values) -> dict:
    values = [v for v in values if v is not None]
    if not values:
        return {"p10": None, "median": None, "p90": None}
    q = np.percentile(np.asarray(values, dtype=float), [10, 50, 90])
    return {
        k: round(float(v), 2) for k, v in zip(("p10", "median", "p90"), q, strict=True)
    }


def pilot_rows(conn) -> list[tuple]:
    """(segment, kwh per sq ft on our area, kwh per sq ft on LBER floor area)."""
    return conn.execute(
        """
        SELECT b.segment, b.grid_kwh / nullif(b.area_sqft, 0),
               b.grid_kwh / nullif((l.attrs->>'Gross_Floor_Area')::float, 0)
        FROM building_evidence b
        JOIN lber_matches m
            ON m.building_id = b.building_id AND m.reporting_year = b.grid_kwh_year
        JOIN raw_lber l USING (reporting_year, objectid)
        WHERE b.electricity_source = 'measured' AND b.segment IS NOT NULL
        """
    ).fetchall()


def healthcare_rows(conn) -> list[float]:
    return [
        r[0]
        for r in conn.execute(
            "SELECT grid_kwh / nullif((attrs->>'Gross_Floor_Area')::float, 0)"
            " FROM raw_lber WHERE grid_kwh IS NOT NULL"
            " AND attrs->>'Property_Type' = 'Healthcare'"
        ).fetchall()
    ]


def summarize(pilot: list[tuple], healthcare: list[float]) -> dict:
    """Per segment: measured count, both spreads, and the prior to use."""
    out = {}
    for seg in sorted({s for s, _, _ in pilot} | set(HEALTHCARE) | set(PROXY_FOR)):
        ours = [a for s, a, _ in pilot if s == seg]
        gfa = [g for s, _, g in pilot if s == seg]
        row = {
            "measured_buildings": len(ours),
            "under_30": len(ours) < MIN_BUILDINGS,
            "our_area": spread(ours),
            "lber_floor_area": spread(gfa),
        }
        if seg in HEALTHCARE:
            row["prior_from"] = "LBER statewide Healthcare, LBER floor area"
            row["prior"] = spread(healthcare)
            row["prior_buildings"] = len(healthcare)
        elif seg in PROXY_FOR:
            row["prior_from"] = f"{PROXY} (proxy, likely understates)"
            row["prior"] = spread(a for s, a, _ in pilot if s == PROXY)
        else:
            row["prior_from"] = "pilot measured, our area"
            row["prior"] = row["our_area"]
        out[seg] = row
    return out


HEADER = """\
# Generated by make intensity from the database (LBER matches from make
# sites). Do not edit by hand. Yearly grid kWh per sq ft. The model uses each
# segment's prior; the funnel uses its median.
"""


def write_config(segments: dict, path: Path = CONFIG_OUT) -> None:
    doc = {
        "status": "sourced",
        "source": (
            "DOER Large Building Energy Reporting, reporting year 2024"
            " (config/lber.yaml), measured grid electricity matched to pilot"
            " buildings in make sites; statewide LBER Healthcare rows for"
            " hospital and other_healthcare."
        ),
        "note": (
            "LBER covers buildings of about 20,000 sq ft and up, so these"
            " priors may not apply to smaller buildings. Nearly every"
            " segment has a low tail (p10 under 1 kWh per sq ft) that is"
            " implausible for an occupied commercial building and points to"
            " partial meter reporting in this first release; it is flagged,"
            " not floored, and it does not shrink with LBER's own floor"
            " area, so it is not an area error. Segments under 30 measured"
            " buildings are flagged."
        ),
        "segments": segments,
        "proxy": {
            "segments": list(PROXY_FOR),
            "from": PROXY,
            "label": "proxy, likely understates",
            "status": "placeholder",
            "note": (
                "Food production, cold storage and laundry have 1 or 2"
                " measured pilot buildings and no LBER property type that"
                " fits. They borrow the manufacturing spread, which is"
                " wide. Their few measured buildings sit above its median,"
                " so it likely understates them."
            ),
            "test": "Compare with measured use of more such buildings.",
            "replace": "A measured spread for each of these segments.",
        },
    }
    path.write_text(
        HEADER + yaml.safe_dump(doc, sort_keys=False, width=88, default_flow_style=None)
    )


def main() -> int:
    with connect() as conn:
        segments = summarize(pilot_rows(conn), healthcare_rows(conn))
    write_config(segments)
    for seg, row in segments.items():
        print(
            f"{seg:18} n={row['measured_buildings']:4}"
            f"{' UNDER 30' if row['under_30'] else '         '}"
            f" ours {row['our_area']}  lber {row['lber_floor_area']}"
            f"  prior {row['prior']} ({row['prior_from']})"
        )
    print(f"wrote {CONFIG_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
